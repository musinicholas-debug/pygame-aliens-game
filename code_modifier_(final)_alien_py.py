def main_menu(screen):
    global current_difficulty

    options = [
        "Commencer une nouvelle partie",
        "Voir les meilleurs scores",
        "Choisir le niveau de difficulté",
        "Quitter le jeu",
    ]

    selected = 0
    clock = pg.time.Clock()

    while True:
        screen.fill((10, 10, 30))

        draw_text(screen, "PYGAME ALIENS", 56, "white", 320, 70)
        draw_text(screen, f"Difficulté actuelle : {current_difficulty}", 28, "cyan", 320, 125)

        for i, option in enumerate(options):
            color = "yellow" if i == selected else "white"
            draw_text(screen, option, 32, color, 320, 200 + i * 50)

        draw_text(screen, "Flèches ↑ ↓ pour naviguer | ENTER pour choisir", 22, "gray", 320, 430)

        pg.display.flip()

        for event in pg.event.get():
            if event.type == pg.QUIT:
                return "quit"

            if event.type == pg.KEYDOWN:
                if event.key == pg.K_UP:
                    selected = (selected - 1) % len(options)

                elif event.key == pg.K_DOWN:
                    selected = (selected + 1) % len(options)

                elif event.key == pg.K_RETURN:
                    if selected == 0:
                        return "play"
                    elif selected == 1:
                        show_high_scores(screen)
                    elif selected == 2:
                        choose_difficulty(screen)
                    elif selected == 3:
                        return "quit"

        clock.tick(40)


def choose_difficulty(screen):
    global current_difficulty

    difficulties = list(DIFFICULTIES.keys())
    selected = difficulties.index(current_difficulty)
    clock = pg.time.Clock()

    while True:
        screen.fill((20, 20, 40))

        draw_text(screen, "CHOISIR LA DIFFICULTÉ", 44, "white", 320, 80)

        for i, diff in enumerate(difficulties):
            color = "yellow" if i == selected else "white"
            draw_text(screen, diff, 36, color, 320, 180 + i * 60)

        draw_text(screen, "ENTER pour confirmer | ESC pour revenir", 24, "gray", 320, 420)

        pg.display.flip()

        for event in pg.event.get():
            if event.type == pg.QUIT:
                pg.quit()
                raise SystemExit

            if event.type == pg.KEYDOWN:
                if event.key == pg.K_UP:
                    selected = (selected - 1) % len(difficulties)

                elif event.key == pg.K_DOWN:
                    selected = (selected + 1) % len(difficulties)

                elif event.key == pg.K_RETURN:
                    current_difficulty = difficulties[selected]
                    return

                elif event.key == pg.K_ESCAPE:
                    return

        clock.tick(40)


def show_high_scores(screen):
    scores = load_high_scores()
    clock = pg.time.Clock()

    while True:
        screen.fill((10, 10, 30))

        draw_text(screen, "MEILLEURS SCORES", 46, "white", 320, 70)

        if not scores:
            draw_text(screen, "Aucun score enregistré.", 30, "gray", 320, 200)
        else:
            for i, item in enumerate(scores):
                text = f"{i + 1}. {item['name']} - {item['score']} pts - {item['difficulty']}"
