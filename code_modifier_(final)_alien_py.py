class Player(pg.sprite.Sprite):
    speed = 10
    bounce = 24
    gun_offset = -11
    images: List[pg.Surface] = []

    def __init__(self, *groups):
        pg.sprite.Sprite.__init__(self, *groups)
        self.image = self.images[0]
        self.rect = self.image.get_rect(midbottom=SCREENRECT.midbottom)
        self.reloading = 0
        self.origtop = self.rect.top
        self.facing = -1
        self.shield = False
        self.double_shot = False

    def move(self, direction):
        if direction:
            self.facing = direction

        self.rect.move_ip(direction * self.speed, 0)
        self.rect = self.rect.clamp(SCREENRECT)

        if direction < 0:
            self.image = self.images[0]
        elif direction > 0:
            self.image = self.images[1]

        self.rect.top = self.origtop - (self.rect.left // self.bounce % 2)

    def gunpos(self):
        pos = self.facing * self.gun_offset + self.rect.centerx
        return pos, self.rect.top


class Alien(pg.sprite.Sprite):
    animcycle = 12
    images: List[pg.Surface] = []

    def __init__(self, speed, *groups):
        pg.sprite.Sprite.__init__(self, *groups)
        self.image = self.images[0]
        self.rect = self.image.get_rect()
        self.facing = random.choice((-1, 1)) * speed
        self.frame = 0

        if self.facing < 0:
            self.rect.right = SCREENRECT.right

    def update(self):
        self.rect.move_ip(self.facing, 0)

        if not SCREENRECT.contains(self.rect):
            self.facing = -self.facing
            self.rect.top = self.rect.bottom + 1
            self.rect = self.rect.clamp(SCREENRECT)

        self.frame += 1
        self.image = self.images[self.frame // self.animcycle % 3]


class Explosion(pg.sprite.Sprite):
    defaultlife = 12
    animcycle = 3
    images: List[pg.Surface] = []

    def __init__(self, actor, *groups):
        pg.sprite.Sprite.__init__(self, *groups)
        self.image = self.images[0]
        self.rect = self.image.get_rect(center=actor.rect.center)
        self.life = self.defaultlife

    def update(self):
        self.life -= 1
        self.image = self.images[self.life // self.animcycle % 2]

        if self.life <= 0:
            self.kill()


class Shot(pg.sprite.Sprite):
    speed = -11
    images: List[pg.Surface] = []

    def __init__(self, pos, *groups):
        pg.sprite.Sprite.__init__(self, *groups)
        self.image = self.images[0]
        self.rect = self.image.get_rect(midbottom=pos)

    def update(self):
        self.rect.move_ip(0, self.speed)

        if self.rect.top <= 0:
            self.kill()


class Bomb(pg.sprite.Sprite):
    speed = 9
    images: List[pg.Surface] = []

    def __init__(self, alien, explosion_group, *groups):
        pg.sprite.Sprite.__init__(self, *groups)
        self.image = self.images[0]
        self.rect = self.image.get_rect(midbottom=alien.rect.move(0, 5).midbottom)
        self.explosion_group = explosion_group

    def update(self):
        self.rect.move_ip(0, self.speed)

        if self.rect.bottom >= 470:
            Explosion(self, self.explosion_group)
            self.kill()


class PowerUp(pg.sprite.Sprite):
    speed = 4
    types = ["shield", "double", "life", "slow"]

    def __init__(self, *groups):
        pg.sprite.Sprite.__init__(self, *groups)

        self.type = random.choice(self.types)
        self.image = pg.Surface((26, 26))
        self.image.fill("black")

        if self.type == "shield":
            color = "cyan"
        elif self.type == "double":
            color = "yellow"
        elif self.type == "life":
            color = "green"
        else:
            color = "purple"

        pg.draw.circle(self.image, color, (13, 13), 12)
        self.image.set_colorkey("black")

        self.rect = self.image.get_rect()
        self.rect.centerx = random.randint(40, SCREENRECT.width - 40)
        self.rect.top = 0

    def update(self):
        self.rect.move_ip(0, self.speed)

        if self.rect.top > SCREENRECT.height:
            self.kill()


class Score(pg.sprite.Sprite):
    def __init__(self, *groups):
        pg.sprite.Sprite.__init__(self, *groups)
        self.font = pg.font.Font(None, 24)
        self.color = "white"
        self.lastscore = -1
        self.lastlives = -1
        self.update()
        self.rect = self.image.get_rect().move(10, 450)

    def update(self):
        global SCORE, LIVES

        if SCORE != self.lastscore or LIVES != self.lastlives:
            self.lastscore = SCORE
            self.lastlives = LIVES
            msg = f"Score: {SCORE}   Lives: {LIVES}"
            self.image = self.font.render(msg, True, self.color)


