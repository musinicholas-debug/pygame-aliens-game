def draw_text(screen, text, size, color, x, y, center=True):
    font = pg.font.Font(None, size)
    image = font.render(text, True, color)
    rect = image.get_rect()

    if center:
        rect.center = (x, y)
    else:
        rect.topleft = (x, y)

    screen.blit(image, rect)


