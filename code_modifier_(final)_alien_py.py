def run_game(screen, winstyle=0, bestdepth=32):
    global SCORE, LIVES

    SCORE = 0
    LIVES = 3

    settings = DIFFICULTIES[current_difficulty]

    fullscreen = False

    img = load_image("player1.gif")
    Player.images = [img, pg.transform.flip(img, 1, 0)]

    img = load_image("explosion1.gif")
    Explosion.images = [img, pg.transform.flip(img, 1, 1)]

    Alien.images = [load_image(im) for im in ("alien1.gif", "alien2.gif", "alien3.gif")]
    Bomb.images = [load_image("bomb.gif")]
    Shot.images = [load_image("shot.gif")]

    icon = pg.transform.scale(Alien.images[0], (32, 32))
    pg.display.set_icon(icon)
    pg.display.set_caption("Pygame Aliens")
    pg.mouse.set_visible(0)

    bgdtile = load_image("background.gif")
    background = pg.Surface(SCREENRECT.size)

    for x in range(0, SCREENRECT.width, bgdtile.get_width()):
        background.blit(bgdtile, (x, 0))

    screen.blit(background, (0, 0))
    pg.display.flip()

    boom_sound = load_sound("boom.wav")
    shoot_sound = load_sound("car_door.wav")

    if pg.mixer:
        music = os.path.join(main_dir, "data", "house_lo.wav")
        pg.mixer.music.load(music)
        pg.mixer.music.play(-1)

    aliens = pg.sprite.Group()
    shots = pg.sprite.Group()
    bombs = pg.sprite.Group()
    powerups = pg.sprite.Group()
    all = pg.sprite.RenderUpdates()
    lastalien = pg.sprite.GroupSingle()

    alienreload = ALIEN_RELOAD
    clock = pg.time.Clock()

    player = Player(all)
    Alien(settings["alien_speed"], aliens, all, lastalien)

    if pg.font:
        all.add(Score(all))

    shield_timer = 0
    double_timer = 0
    slow_timer = 0
    powerup_timer = 0

    while player.alive():
        for event in pg.event.get():
            if event.type == pg.QUIT:
                return "quit"

            if event.type == pg.KEYDOWN and event.key == pg.K_ESCAPE:
                return "menu"

            elif event.type == pg.KEYDOWN and event.key == pg.K_f:
                if not fullscreen:
                    screen_backup = screen.copy()
                    screen = pg.display.set_mode(
                        SCREENRECT.size,
                        winstyle | pg.FULLSCREEN,
                        bestdepth
                    )
                    screen.blit(screen_backup, (0, 0))
                else:
                    screen_backup = screen.copy()
                    screen = pg.display.set_mode(
                        SCREENRECT.size,
                        winstyle,
                        bestdepth
                    )
                    screen.blit(screen_backup, (0, 0))

                pg.display.flip()
                fullscreen = not fullscreen

        keystate = pg.key.get_pressed()

        all.clear(screen, background)
        all.update()

        # Timers des power-ups
        if shield_timer > 0:
            shield_timer -= 1
            player.shield = True
        else:
            player.shield = False

        if double_timer > 0:
            double_timer -= 1
            player.double_shot = True
        else:
            player.double_shot = False

        if slow_timer > 0:
            slow_timer -= 1
            alien_speed = max(3, settings["alien_speed"] // 2)
        else:
            alien_speed = settings["alien_speed"]

        # Mouvement du joueur
        direction = keystate[pg.K_RIGHT] - keystate[pg.K_LEFT]
        player.move(direction)

        # Tir du joueur
        firing = keystate[pg.K_SPACE]

        if not player.reloading and firing and len(shots) < MAX_SHOTS:
            if player.double_shot:
                Shot((player.rect.centerx - 12, player.rect.top), shots, all)
                Shot((player.rect.centerx + 12, player.rect.top), shots, all)
            else:
                Shot(player.gunpos(), shots, all)

            if pg.mixer and shoot_sound is not None:
                shoot_sound.play()

        player.reloading = firing

        # Création des aliens
        if alienreload:
            alienreload -= 1
        elif len(aliens) < settings["max_aliens"] and not int(random.random() * settings["alien_odds"]):
            Alien(alien_speed, aliens, all, lastalien)
            alienreload = ALIEN_RELOAD

        # Bombes ennemies
        if lastalien and not int(random.random() * settings["bomb_odds"]):
            Bomb(lastalien.sprite, all, bombs, all)

        # Apparition des power-ups
        powerup_timer += 1

        if powerup_timer > 350:
            if random.randint(1, 100) <= 35:
                PowerUp(powerups, all)
            powerup_timer = 0

        # Collision joueur / power-up
        for powerup in pg.sprite.spritecollide(player, powerups, True):
            if powerup.type == "shield":
                shield_timer = 300
            elif powerup.type == "double":
                double_timer = 300
            elif powerup.type == "life":
                LIVES += 1
            elif powerup.type == "slow":
                slow_timer = 300

        # Collision alien / joueur
        for alien in pg.sprite.spritecollide(player, aliens, True):
            if pg.mixer and boom_sound is not None:
                boom_sound.play()

            Explosion(alien, all)

            if player.shield:
                shield_timer = 0
            else:
                LIVES -= 1
                Explosion(player, all)

                if LIVES <= 0:
                    player.kill()

        # Collision tir / alien
        for alien in pg.sprite.groupcollide(aliens, shots, True, True).keys():
            if pg.mixer and boom_sound is not None:
                boom_sound.play()

            Explosion(alien, all)
            SCORE += 1

        # Collision bombe / joueur
        for bomb in pg.sprite.spritecollide(player, bombs, True):
            if pg.mixer and boom_sound is not None:
                boom_sound.play()

            Explosion(bomb, all)

            if player.shield:
                shield_timer = 0
            else:
                LIVES -= 1
                Explosion(player, all)

                if LIVES <= 0:
                    player.kill()

        # Affichage des effets actifs
        if player.shield:
            draw_text(screen, "BOUCLIER", 22, "cyan", 560, 20)

        if player.double_shot:
            draw_text(screen, "DOUBLE TIR", 22, "yellow", 550, 45)

        if slow_timer > 0:
            draw_text(screen, "RALENTI", 22, "purple", 560, 70)

        dirty = all.draw(screen)
        pg.display.update(dirty)
        clock.tick(40)

    if pg.mixer:
        pg.mixer.music.fadeout(1000)

    pg.time.wait(1000)
    return "game_over"


